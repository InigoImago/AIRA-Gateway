"""The console's copy of the OpenCode plugin is the plugin (`FRD-144`).

The panel that issues a key offers the plugin for download, which needs the file's text inside the
Angular bundle. That is a second copy of a file, and a second copy is a second thing that can
disagree — so it is generated, and this fails when it is stale.

Why it matters more than it looks: the copy nobody regenerates is the one a developer installs. A
plugin that is a version behind does not announce itself; it shows a figure, and the figure is the
whole point of the feature.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "tools" / "opencode_plugin_asset.py"
TARGET = ROOT / "management/frontend/src/app/features/use-cases/opencode-plugin.generated.ts"
PLUGIN = ROOT / "tools" / "opencode" / "plugins" / "aira-budget" / "tui.tsx"


def test_the_generated_copy_is_current() -> None:
    result = subprocess.run(  # noqa: S603 - a fixed argv, no shell
        [sys.executable, str(GENERATOR)], capture_output=True, text=True, cwd=ROOT, timeout=60
    )

    assert result.returncode == 0, (
        f"{result.stdout.strip()}\n"
        "Run `uv run python tools/opencode_plugin_asset.py --write` and commit the result."
    )


def test_the_copy_is_the_whole_plugin_and_nothing_else() -> None:
    """Not a paraphrase and not a trimmed version: the browser has to produce the file itself."""
    import json
    import re

    encoded = re.search(
        r"export const OPENCODE_BUDGET_PLUGIN = (\".*\");", TARGET.read_text(), re.S
    )
    assert encoded, "the constant is not where the generator puts it"

    assert json.loads(encoded.group(1)) == PLUGIN.read_text()


def test_the_asset_is_not_hand_edited() -> None:
    """The header says so, and a reader who edits it anyway loses the edit on the next generation.

    Stated as a check because the file is a plausible place to fix a typo in: it is TypeScript, it
    is in the Angular tree, and nothing about its content looks generated.
    """
    assert TARGET.read_text().startswith("// GENERATED by tools/opencode_plugin_asset.py")
