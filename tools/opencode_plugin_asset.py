"""Carry the OpenCode budget plugin into the Angular bundle, so the console can hand it out.

The plugin (`tools/opencode/plugin/aira-budget.js`) is a file a developer installs into their own
OpenCode. The console is where they get their API key, which makes it the one place they are
certain to look — so the API-keys panel offers the plugin beside the configuration, and a feature
whose discovery depends on reading `tools/opencode/README.md` becomes one that does not.

That needs the file's text inside the Angular application, and a second copy of a file is a second
thing that can disagree. So the copy is **generated** and a test fails when it is stale, the same
arrangement `tools/features_index.py` uses for the feature index.

    uv run python tools/opencode_plugin_asset.py --write    # after editing the plugin
    uv run python tools/opencode_plugin_asset.py            # print, exit 1 when stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "opencode" / "plugin" / "aira-budget.js"
TARGET = (
    ROOT
    / "management"
    / "frontend"
    / "src"
    / "app"
    / "features"
    / "use-cases"
    / "opencode-plugin.generated.ts"
)

HEADER = """// GENERATED by tools/opencode_plugin_asset.py — do not edit.
//
// The text of `tools/opencode/plugin/aira-budget.js`, so the API-keys panel can offer the plugin
// beside the configuration it already generates (`FRD-139` §5). One source, a generated copy, and
// `tools/tests/test_the_console_hands_out_the_plugin_it_ships.py` fails when they disagree.
//
// It is one string rather than a module because what the browser must produce is the **file**: a
// developer saves it into `.opencode/plugin/`, where OpenCode loads every file in the directory.
"""


def rendered() -> str:
    """The plugin as one TypeScript string constant.

    JSON-encoded rather than a template literal: the plugin contains backticks and `${…}` of its
    own, and a template literal would evaluate them — which is the kind of mistake that produces a
    file that looks right and runs differently.
    """
    return f"{HEADER}\nexport const OPENCODE_BUDGET_PLUGIN = {json.dumps(SOURCE.read_text())};\n"


def main() -> int:
    text = rendered()
    if "--write" in sys.argv:
        TARGET.write_text(text)
        print(f"wrote {TARGET.relative_to(ROOT)}")
        return 0
    current = TARGET.read_text() if TARGET.exists() else ""
    if current == text:
        print(f"{TARGET.relative_to(ROOT)} is current")
        return 0
    print(f"{TARGET.relative_to(ROOT)} is stale — run with --write")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
