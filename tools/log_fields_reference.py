"""Write the field table of `docs/LOGGING.md` from the register the code writes lines by.

    uv run python tools/log_fields_reference.py --write    # after a field was added or changed
    uv run python tools/log_fields_reference.py            # prints it, changes nothing

A table of fields written by hand is the second copy of the register, and the copy nobody opens
goes stale; `tools/tests/test_the_logging_reference_is_the_register.py` fails when the two differ.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCUMENT = ROOT / "docs" / "LOGGING.md"

BEGIN = "<!-- fields: generated by tools/log_fields_reference.py — edit the register, not this -->"
END = "<!-- fields: end -->"

#: How each kind of field reads to somebody who receives the lines.
KIND_WORDS = {
    "plain": "as it is",
    "person": "a pseudonym under strict data mode",
    "address": "as `AIRA_TELEMETRY_IP` says",
}


def table() -> str:
    from aira_common.logging.fields import FIELDS

    rows = [
        "| Field | Type | Written | What it says |",
        "| ----- | ---- | ------- | ------------ |",
    ]
    for name in sorted(FIELDS):
        field = FIELDS[name]
        meaning = field.meaning.replace("|", "\\|")
        rows.append(f"| `{name}` | {field.type} | {KIND_WORDS[str(field.kind)]} | {meaning} |")
    return "\n".join(rows)


def rendered(document: str) -> str:
    head, found, rest = document.partition(BEGIN)
    if not found:
        raise SystemExit(f"{DOCUMENT} has no `{BEGIN}` marker")
    _, found, tail = rest.partition(END)
    if not found:
        raise SystemExit(f"{DOCUMENT} has no `{END}` marker")
    return f"{head}{BEGIN}\n\n{table()}\n\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the table into the document")
    args = parser.parse_args(argv)
    if args.write:
        DOCUMENT.write_text(rendered(DOCUMENT.read_text(encoding="utf-8")), encoding="utf-8")
        return 0
    print(table())
    return 0


if __name__ == "__main__":
    sys.exit(main())
